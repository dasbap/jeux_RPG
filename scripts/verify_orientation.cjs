const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require(require.resolve('jsdom', {paths:[path.join(__dirname,'..','.ui-test'),__dirname]}));
const dom = new JSDOM('<main><button id="play">Jouer</button></main>', {runScripts:'outside-only'});
const w = dom.window;
let change, clicks=0, keys=0, blurs=0, stops=0;
const media={matches:false,addEventListener:(_type,callback)=>{change=callback;}};
w.matchMedia=()=>media;
w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
w.HTMLDialogElement.prototype.close=function(){this.open=false;};
w.RPGMotion={set:vector=>{assert.deepEqual(Array.from(vector),[0,0]);stops++;}};
w.addEventListener('blur',()=>blurs++);
w.eval(fs.readFileSync(path.join(__dirname,'../jeuxRPG/multiplayer/web/mobile_controls.js'),'utf8'));
const play=w.document.getElementById('play');
play.addEventListener('click',()=>clicks++);
w.addEventListener('keydown',()=>keys++);
play.focus();play.click();
assert.equal(clicks,1);
media.matches=true;change();
assert(w.RPGLandscape.blocked);
const dialog=w.document.getElementById('landscape-required');
assert(dialog.open);assert.equal(blurs,1);assert.equal(stops,1);
play.click();
w.dispatchEvent(new w.KeyboardEvent('keydown',{key:'g',cancelable:true}));
assert.equal(clicks,1);assert.equal(keys,0);
assert.equal(dialog.dispatchEvent(new w.Event('cancel',{cancelable:true})),false);
// Loading completion must not re-enable portrait gameplay.
w.document.querySelector('main').inert=false;
play.click();assert.equal(clicks,1);assert(dialog.open);
w.document.dispatchEvent(new w.Event('fullscreenchange'));assert(dialog.open);
media.matches=false;change();
assert(!w.RPGLandscape.blocked);assert(!dialog.open);
assert.equal(w.document.activeElement,play);
play.click();assert.equal(clicks,2);
media.matches=true;change();assert(dialog.open);assert.equal(stops,2);
assert.equal(w.document.querySelectorAll('#landscape-required').length,1);
dom.window.close();
console.log('Orientation vérifiée : entrées bloquées en portrait, mouvement arrêté, reprise en paysage.');

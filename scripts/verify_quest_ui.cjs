"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {JSDOM,VirtualConsole}=require("../.ui-test/node_modules/jsdom");
const fixtures=JSON.parse(fs.readFileSync(process.argv[2],"utf8"));
const web=path.join(__dirname,"../jeuxRPG/multiplayer/web");
const errors=[];
const console=new VirtualConsole();console.on("jsdomError",error=>errors.push(error.message));
const dom=new JSDOM(fs.readFileSync(path.join(web,"index.html"),"utf8"),{url:"http://ui.test",runScripts:"outside-only",virtualConsole:console});
dom.window.setInterval=()=>0;
dom.window.eval(fs.readFileSync(path.join(web,"map_artwork.js"),"utf8"));
dom.window.eval(require("./client_source.cjs")()+`
 refresh=async()=>{};scheduleRefresh=()=>{};
 window.questAudit={render:adventure=>{token='audit';session={id:'audit',state:'running',revision:1,me:adventure.players[0].id,tutorial:adventure,events:[]};renderGame(adventure);}};
`);
const el=id=>dom.window.document.getElementById(id);
const render=fixture=>dom.window.questAudit.render(JSON.parse(JSON.stringify(fixture)));
render(fixtures.locked);
assert(el("forge-status").textContent.includes("Mira"));
assert.equal(el("forge-catalogue").querySelectorAll("[data-action]").length,10);
assert([...el("forge-catalogue").querySelectorAll("[data-action]")].every(button=>button.disabled),"La forge de Rosée est verrouillée avant la remise de Mira");
render(fixtures.unlocked);
assert([...el("forge-catalogue").querySelectorAll("[data-action]")].every(button=>!button.disabled),"Les recettes abordables sont disponibles après déblocage");
const category=el("quest-category"),categoryLabel=category.parentElement;
category.focus();
const observer=new dom.window.MutationObserver(()=>{});
observer.observe(categoryLabel.parentElement,{childList:true});
observer.observe(category,{attributes:true,subtree:true});
for(let tick=0;tick<10;tick++)render(fixtures.unlocked);
const changes=observer.takeRecords();observer.disconnect();
assert(!changes.some(change=>[...change.removedNodes].includes(categoryLabel)),"Le filtre reste attaché au DOM pendant les rafraîchissements");
assert(!changes.some(change=>change.type==="attributes"),"Les options inchangées ne sont pas modifiées pendant l’ouverture du filtre");
assert.equal(dom.window.document.activeElement,category,"Le filtre conserve le focus pendant les rafraîchissements");
el("quest-category").value="upgrade";el("quest-category").dispatchEvent(new dom.window.Event("change"));
assert.equal(el("quest-list").querySelectorAll(".quest-card").length,4);
assert([...el("quest-list").querySelectorAll(".quest-status")].every(node=>/Perfectionnement.*Facultative/.test(node.textContent)));
el("quest-list").querySelector('[data-track-quest="upgrade_casque_schiste"]').click();
const upgradeName=fixtures.unlocked.quest_journal.find(quest=>quest.id==="upgrade_casque_schiste").name;
assert(el("quest-actions").textContent.includes(upgradeName));
assert(el("hud-objective").textContent.includes(upgradeName));
assert(el("quest-list").textContent.includes("+0 / +2 requis"));
el("quest-category").value="crafting";el("quest-category").dispatchEvent(new dom.window.Event("change"));
assert.equal(el("quest-list").querySelectorAll(".quest-card").length,4);
assert([...el("quest-list").querySelectorAll(".quest-status")].every(node=>/Artisanat.*Facultative/.test(node.textContent)));
const blocked=JSON.parse(JSON.stringify(fixtures.unlocked));
const followup=blocked.quest_journal.find(quest=>quest.id==="upgrade_casque_schiste");
followup.status="locked";followup.missing_requirements=["quête à terminer : Casque de Schiste"];
render(blocked);
el("quest-category").value="upgrade";el("quest-category").dispatchEvent(new dom.window.Event("change"));
const lockedCard=el("quest-list").querySelector('[data-quest="upgrade_casque_schiste"]');
assert(lockedCard.querySelector(".quest-status").textContent.includes("Prérequis à remplir"));
assert(lockedCard.textContent.includes("Suite de :"));
assert(lockedCard.textContent.includes("quête à terminer : Casque de Schiste"));
assert.equal(lockedCard.querySelector("[data-track-quest]"),null);
render(fixtures.panoplie);
const panoplie=el("equipment-set-details").querySelector('[data-set="lisiere"]');
assert(panoplie.textContent.includes("5 pièce(s) équipée(s)"));
assert.equal(panoplie.querySelectorAll(".set-tier.active").length,3);
assert(panoplie.querySelector(".set-total").textContent.includes("+12 PV"));
assert.equal(el("forge-catalogue").querySelectorAll(".set-membership").length,6);
render(fixtures.panoplie_mixed);
const mixed=el("equipment-set-details").querySelector('[data-set="lisiere"]');
assert(mixed.textContent.includes("4 pièce(s) équipée(s)"));
assert.equal(mixed.querySelectorAll(".set-tier.active").length,2);
assert(!mixed.querySelector('[data-pieces="5"]').classList.contains("active"));
assert(mixed.querySelector(".set-total").textContent.includes("+4 PV"));
assert.deepEqual(errors,[]);
dom.window.close();
process.stdout.write("Interface vérifiée : forge verrouillée/débloquée, dix recettes, catégories et suivi des paliers d’amélioration.\n");

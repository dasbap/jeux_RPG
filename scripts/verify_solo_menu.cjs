"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const {JSDOM} = require(require.resolve("jsdom", {paths: [path.join(__dirname, "..", ".ui-test")]}));
const root = path.join(__dirname, "../jeuxRPG/multiplayer/web");
const dom = new JSDOM(fs.readFileSync(path.join(root, "index.html"), "utf8"), {url: "https://game.vercel.app/", runScripts: "outside-only"});
const w = dom.window;
w.structuredClone = structuredClone;
w.sessionStorage.setItem("rpg-token", "online-token");
w.fetch = async url => { assert.equal(url, "/api/classes"); return {ok: true, json: async () => []}; };
w.setTimeout = () => 1;
w.setInterval = () => 1;
let onlineCalls = 0, localCalls = 0, closed = false;
const online = {connected: false, close() {}, request: async () => {onlineCalls++; return {ok: true, json: async () => ({account: {username: "Online"}, characters: [], selected: null})}; }};
w.rpgRealtime = online;
w.createRpgSoloTransport = async () => ({connected: true, subscribe() {}, flush: async () => {}, close: async () => {closed = true;}, request: async url => {
  localCalls++;
  assert(["/api/account/me", "/api/classes"].includes(url));
  return {ok: true, json: async () => url === "/api/classes" ? [{id: "Knight", name: "Chevalier"}] : {account: {username: "Solo"}, characters: [{id: "local", name: "Local", class_name: "Knight"}], selected: "local", token: "local-token"}};
}});
w.eval(require("./client_source.cjs")() + ';window.mode = () => gameMode; window.localToken = () => token; window.switchMode = switchGameMode;');
(async () => {
  await new Promise(resolve => setImmediate(resolve));
  onlineCalls = 0;
  await w.switchMode("solo");
  assert.equal(w.mode(), "solo");
  assert.equal(w.localToken(), "local-token");
  assert.equal(w.sessionStorage.getItem("rpg-token"), "online-token");
  assert.equal(onlineCalls, 0);
  assert.equal(localCalls, 2);
  assert.equal(w.document.getElementById("characters").hidden, false);
  assert.match(w.document.getElementById("character-list").textContent, /Local/);
  assert.equal(w.document.getElementById("show-social").hidden, true);
  await w.switchMode("online");
  assert(closed);
  assert.equal(w.localToken(), "online-token");
  assert.equal(w.rpgRealtime, online);
  assert.equal(onlineCalls, 1);
  assert.doesNotMatch(w.document.getElementById("character-list").textContent, /Local/);
  console.log("Menu Solo / En ligne : choix, personnages et sessions isolés, restauration du mode en ligne vérifiés.");
  dom.window.close();
})().catch(error => {console.error(error); dom.window.close(); process.exitCode = 1;});
